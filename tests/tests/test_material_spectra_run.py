def test_convergence_sweep_records_and_analysis(sweep):
    """SPEC-013-002: three density levels x three temperatures; conserved
    split-mesh weights; per-block deltas + verdict + numeric statement."""
    script, _block, _magnon, records, analysis, statement = sweep
    assert len(records) == 9
    levels = [record["level"] for record in records[::3]]
    assert levels == ["declared", "split3", "split5"]
    assert [r["phonon_mesh_sizes"]["K"] for r in records[::3]] == [1, 3, 5]
    assert [r["temperature_K"] for r in records[:3]] == [15.0, 30.0, 45.0]
    for record in records:
        assert np.isfinite(record["magnon"]["spectral_max"])
        for entry in record["blocks"].values():
            assert np.isfinite(entry["max_abs_sigma"])
            assert np.isfinite(entry["max_abs_delta_d"])
    # split-mesh weights stay normalized per declared point
    base = {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))}
    for offsets in ((0.01,), (0.01, 0.005)):
        _points, weights = script.sweep_phonon_loop_meshes(base, offsets)[
            tuple(np.round(K_POINT, 12))
        ]
        np.testing.assert_allclose(weights.sum(), 1.0)
        assert len(weights) == 1 + 2 * len(offsets)
    assert set(analysis) >= {
        "declaration",
        "levels",
        "temperatures_K",
        "density_deltas_at_30K",
        "temperature_deltas_finest_level",
        "verdict",
        "records",
    }
    assert analysis["verdict"]["converged"] in (True, False)
    assert "convergence" in statement and "%" in statement


