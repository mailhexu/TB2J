K_POINT = np.array([1.0 / 3.0, 1.0 / 3.0, 0.0])
M_POINT = np.array([0.5, 0.0, 0.0])

_SCRIPT_MODULE = None


def _script():
    """Import scripts/s013_material_run.py as a module (cached)."""
    global _SCRIPT_MODULE
    if _SCRIPT_MODULE is None:
        spec = importlib.util.spec_from_file_location(
            "s013_material_run_script", SCRIPT_PATH
        )
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _SCRIPT_MODULE = module
    return _SCRIPT_MODULE


def _settings():
    return MaterialSettings(omega_points=161)


def _run_once():
    record = json.loads(FIXTURE.read_text())
    block = block_from_fixture(record)
    magnon = cri3_magnon_model(j0_eV=record["magnon"]["j0_eV"])
    coupled = run_coupled_spectra(
        magnon,
        [block],
        _settings(),
        [K_POINT.copy(), M_POINT.copy()],
        {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
    )
    path = magnon.get_site_boson_modes([np.zeros(3), K_POINT.copy(), M_POINT.copy()])
    return block, coupled, np.asarray(path.energies, dtype=float)


