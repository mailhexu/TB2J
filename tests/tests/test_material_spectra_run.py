def test_manifest_reference_validation_records_status(tmp_path):
    """STD-013-003: present referenced files are hashed ('resolved'), absent
    ones recorded 'unresolved' — in the returned dict and the manifest."""
    record = json.loads(FIXTURE.read_text())
    block = block_from_fixture(record)
    qualification = tmp_path / "qualification-report.json"
    qualification.write_text('{"qualified": true}')
    manifest = provenance_manifest(
        _settings(),
        FIXTURE,
        [block],
        [K_POINT.copy()],
        {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
        extra={
            "s002_store": {"path": str(tmp_path / "absent.json"), "sha256": "0" * 64},
            "s012_qualification_report": {
                "path": str(qualification),
                "sha256": sha256_file(qualification),
            },
        },
    )
    statuses = validate_manifest(manifest, FIXTURE)
    assert statuses["s012_qualification_report"] == "resolved"
    assert statuses["s002_store"] == "unresolved"
    assert statuses["blocks[0]"] == "unresolved"
    assert manifest["reference_validation"] == statuses
