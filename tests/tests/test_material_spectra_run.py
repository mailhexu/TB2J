def test_test001_artifact_writer_bytes_reproducible(tmp_path, sweep):
    """TEST-001 (round-1): the artifact WRITERS are exercised twice into two
    separate directories and s013_spectra.npz, s013_summary.json and
    s013_manifest.json are compared byte-wise.

    Plot exclusion (stated reason): the PNG writers are matplotlib-version-
    dependent rendering, not part of the numeric artifact contract, so they
    sit outside the formal byte comparison (they are nonetheless observed
    byte-identical across reruns in this environment); the plotted
    quantities are exactly the byte-compared npz/summary arrays.
    """
    script, block, magnon, _records, analysis, statement = sweep
    coupled = run_coupled_spectra(
        magnon,
        [block],
        _settings(),
        [K_POINT.copy(), M_POINT.copy()],
        {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
    )
    path_data = bare_magnon_dispersion(magnon, n_points=61)
    manifest_extra = {
        "code_revision": "test",
        "s002_store": {"path": "fixture", "sha256": "0" * 64},
        "s012_qualification_report": {"path": "fixture", "sha256": "0" * 64},
        "s012_campaign": {"path": "fixture", "campaign_id": "s012-h005-3x"},
        "magnon_model": {"j0_meV": 1.529241586},
        "phonon_qualified": {"gamma": {"q": [0.0, 0.0, 0.0]}},
        "declaration": "fixture test declaration",
    }
    outputs = []
    for run in ("first", "second"):
        outdir = tmp_path / run
        outdir.mkdir()
        outputs.append(
            script.write_numeric_artifacts(
                outdir,
                _settings(),
                [block],
                [],
                path_data,
                _phonon_qualified(),
                coupled,
                [K_POINT.copy(), M_POINT.copy()],
                {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
                FIXTURE,
                manifest_extra,
                THERMAL_PRESCRIPTION + " " + statement,
                analysis,
            )
        )
        del outdir
    for name in ("s013_spectra.npz", "s013_summary.json", "s013_manifest.json"):
        first = (tmp_path / "first" / name).read_bytes()
        second = (tmp_path / "second" / name).read_bytes()
        assert first == second, name
    with np.load(tmp_path / "first" / "s013_spectra.npz") as archive:
        assert set(archive.files) >= {
            "magnon_sigma",
            "magnon_spectral",
            "omega_grid_eV",
        }
    summary = outputs[0]["summary"]
    assert summary["schema"] == "s013-material-run-summary-v2"
    assert summary["convergence"]["records"], "sweep records missing from summary"
    manifest = outputs[0]["manifest"]
    assert manifest["schema"] == MANIFEST_SCHEMA
    assert "records" not in manifest["convergence"]
    assert manifest["thermal_prescription"].endswith(
        "The declared M+M->Gamma exclusion is kept in every level."
    )


def test_make_plots_three_magnon_panels_then_phonons(tmp_path, sweep):
    """STD-013-001/002: three magnon panels first, phonon panels after; the
    phonon markers sit at bare_energies_eV * 1e3 (already eV, no second
    thz_to_ev)."""
    script, block, _magnon, _records, _analysis, _statement = sweep
    magnon = _script_magnon()
    # production declared magnon loop: Gamma, K, M (three panels)
    coupled = run_coupled_spectra(
        magnon,
        [block],
        _settings(),
        [np.zeros(3), K_POINT.copy(), M_POINT.copy()],
        {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
    )
    path_data = bare_magnon_dispersion(magnon, n_points=9)
    fig = script.make_plots(tmp_path, path_data, coupled, _phonon_qualified(), [block])
    n_panels = 3 + len(coupled["phonon"])
    assert len(fig.axes) == n_panels
    titles = [ax.get_title() for ax in fig.axes]
    assert titles[:3] == ["A(k, w), k=Gamma", "A(k, w), k=K", "A(k, w), k=M"]
    assert titles[3].startswith("phonon Im deltaD")
    # phonon markers: exactly the bare energies in meV
    expected = np.sort(
        np.atleast_1d(np.asarray(coupled["phonon"][0]["bare_energies_eV"])) * 1e3
    )
    markers = np.sort(
        [
            line.get_xdata()[0]
            for ax in fig.axes[3:]
            for line in ax.lines
            if line.get_linestyle() == "--"
        ]
    )
    np.testing.assert_allclose(markers, expected)
    # magnon markers per panel
    for i_k in range(3):
        panel_markers = [
            line.get_xdata()[0]
            for line in fig.axes[i_k].lines
            if line.get_linestyle() == "--"
        ]
        np.testing.assert_allclose(
            np.sort(panel_markers),
            np.sort(coupled["magnon"]["bare_energies_eV"][i_k] * 1e3),
        )


