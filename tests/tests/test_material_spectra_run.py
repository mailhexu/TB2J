def test_test002_manifest_completeness_and_hash(tmp_path):
    """TEST-002: every manifest field is non-empty and the fixture hash
    matches the fixture file."""
    record = json.loads(FIXTURE.read_text())
    block = block_from_fixture(record)
    settings = _settings()
    meshes = {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))}
    manifest_path = tmp_path / "manifest.json"
    manifest = provenance_manifest(
        settings,
        FIXTURE,
        [block],
        [K_POINT.copy(), M_POINT.copy()],
        meshes,
        extra={
            "code_revision": "test",
            "s002_store": {"path": "fixture", "sha256": "0" * 64},
            "s012_qualification_report": {
                "path": "fixture",
                "sha256": "0" * 64,
            },
            "s012_campaign": {"path": "fixture", "campaign_id": "s012-h005-3x"},
            "magnon_model": {"j0_meV": 1.529241586},
            "phonon_qualified": {"gamma": {"q": [0.0, 0.0, 0.0]}},
            "declaration": "fixture test declaration",
        },
    )
    manifest_path.write_text(json.dumps(manifest))
    loaded = json.loads(manifest_path.read_text())
    statuses = validate_manifest(loaded, FIXTURE)
    assert manifest["schema"] == MANIFEST_SCHEMA == loaded["schema"]
    assert manifest["approximation"]
    assert manifest["thermal_prescription"] == THERMAL_PRESCRIPTION
    assert manifest["mixing_availability"] == MIXING_UNAVAILABLE_STATEMENT
    assert "no interpolated leg" in manifest["interpolation_status"]
    # STD-013-003: referenced files absent from this fixture manifest are
    # recorded 'unresolved', never silently trusted
    assert statuses == loaded["reference_validation"]
    assert set(statuses) == {
        "s002_store",
        "s012_qualification_report",
        "blocks[0]",
    }
    assert set(statuses.values()) == {"unresolved"}


