"""Story-013 material run gates (TEST-001/002) on the cached fixture.

The fixture ``data/s013_fixture_k_acoustic_like.json`` was generated by
``scripts/s013_material_run.py`` from the qualified S002 K-point store; the
tests never touch SIESTA or any external file.  TEST-001 reruns the
deterministic pipeline twice and compares every numeric artifact; TEST-002
validates the provenance-manifest schema (all fields non-empty, fixture
hash matches).
"""

import json
from pathlib import Path

import numpy as np
import pytest

from TB2J.magnon_phonon.material import (
    FIXTURE_SCHEMA,
    MIXING_UNAVAILABLE_STATEMENT,
    THERMAL_PRESCRIPTION,
    MaterialSettings,
    block_from_fixture,
    cri3_magnon_model,
    provenance_manifest,
    run_coupled_spectra,
    validate_manifest,
)

FIXTURE = Path(__file__).parent / "data" / "s013_fixture_k_acoustic_like.json"
K_POINT = np.array([1.0 / 3.0, 1.0 / 3.0, 0.0])
M_POINT = np.array([0.5, 0.0, 0.0])


def _settings():
    return MaterialSettings(omega_points=161)


def _run_once():
    record = json.loads(FIXTURE.read_text())
    block = block_from_fixture(record)
    magnon = cri3_magnon_model(j0_eV=record["magnon"]["j0_eV"])
    coupled = run_coupled_spectra(
        magnon,
        [block],
        _settings(),
        [K_POINT.copy(), M_POINT.copy()],
        {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
    )
    path = magnon.get_site_boson_modes([np.zeros(3), K_POINT.copy(), M_POINT.copy()])
    return block, coupled, np.asarray(path.energies, dtype=float)


def _artifact_digest(coupled):
    return {
        "magnon_bare": coupled["magnon"]["bare_energies_eV"],
        "magnon_sigma": coupled["magnon"]["sigma"],
        "magnon_spectral": coupled["magnon"]["spectral"],
        "phonon_sigma": coupled["phonon"][0]["sigma"],
        "phonon_delta_d": coupled["phonon"][0]["delta_d"],
        "phonon_bare": coupled["phonon"][0]["bare_energies_eV"],
        "omega": coupled["omega_grid_eV"],
    }


def test_fixture_schema():
    record = json.loads(FIXTURE.read_text())
    assert record["schema"] == FIXTURE_SCHEMA
    assert record["block"]["mode"] == "acoustic-like"
    assert record["block"]["evidence_sha256"].startswith("0aa53788")


def test_test001_rerun_numeric_reproducibility():
    """TEST-001: two pipeline runs produce identical numeric artifacts."""
    first = _artifact_digest(_run_once()[1])
    second = _artifact_digest(_run_once()[1])
    for key in first:
        assert np.array_equal(first[key], second[key]), key


def test_test001_bare_magnon_goldstone_and_k_degeneracy():
    """The bare magnon reference is the declared FM model: exact Gamma
    goldstone and degenerate K branches."""
    _, _, path_energies = _run_once()
    assert path_energies[0, 0] == 0.0
    a, b = path_energies[1]
    assert a == pytest.approx(b, rel=1e-12)
    assert np.all(path_energies >= 0.0)


def test_test002_manifest_completeness_and_hash(tmp_path):
    """TEST-002: every manifest field is non-empty and the fixture hash
    matches the fixture file."""
    record = json.loads(FIXTURE.read_text())
    block = block_from_fixture(record)
    settings = _settings()
    meshes = {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))}
    manifest_path = tmp_path / "manifest.json"
    manifest = provenance_manifest(
        settings,
        FIXTURE,
        [block],
        [K_POINT.copy(), M_POINT.copy()],
        meshes,
        extra={
            "code_revision": "test",
            "s002_store": {"path": "fixture", "sha256": "0" * 64},
            "s012_qualification_report": {
                "path": "fixture",
                "sha256": "0" * 64,
            },
            "s012_campaign": {"path": "fixture", "campaign_id": "s012-h005-3x"},
            "magnon_model": {"j0_meV": 1.529241586},
            "phonon_qualified": {"gamma": {"q": [0.0, 0.0, 0.0]}},
            "declaration": "fixture test declaration",
        },
    )
    manifest_path.write_text(json.dumps(manifest))
    validate_manifest(json.loads(manifest_path.read_text()), FIXTURE)
    assert manifest["approximation"]
    assert manifest["thermal_prescription"] == THERMAL_PRESCRIPTION
    assert manifest["mixing_availability"] == MIXING_UNAVAILABLE_STATEMENT
    assert "no interpolated leg" in manifest["interpolation_status"]


def test_manifest_rejects_empty_field(tmp_path):
    record = json.loads(FIXTURE.read_text())
    block = block_from_fixture(record)
    manifest = provenance_manifest(
        _settings(),
        FIXTURE,
        [block],
        [K_POINT.copy()],
        {tuple(np.round(K_POINT, 12)): ([K_POINT.copy()], np.array([1.0]))},
    )
    manifest["declaration"] = ""
    with pytest.raises(ValueError, match="empty"):
        validate_manifest(manifest, FIXTURE)


