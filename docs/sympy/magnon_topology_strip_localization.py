"""Executable certificate for physical spin-amplitude strip localization.

The strip solver receives Colpa physical Nambu modes (u, v). The certificate
shows that the sum of the squared transverse spin-amplitude matrix elements is
S (|u|^2 + |v|^2), and that generalized projected edge fractions do not
change under a unitary basis rotation inside a degenerate subspace.
"""

from pathlib import Path

import sympy as sp

REPORT = []


def check(condition, message):
    if not condition:
        raise AssertionError(f"CERTIFICATE FAILED: {message}")
    REPORT.append(f"[OK] {message}")
    print(f"  [OK] {message}")


def named_expressions():
    """Return the expressions pinned by this certificate."""
    return {
        "transverse_x_amplitude": "sqrt(S/2) * (u + v)",
        "transverse_y_amplitude": "-I * sqrt(S/2) * (u - v)",
        "physical_spin_amplitude_weight": "S * (|u|^2 + |v|^2)",
        "normalized_site_fraction": "site_weight / sum(site_weight)",
        "degenerate_projected_fraction": "eig(L, T), L=Psi^dag W_edge Psi, T=Psi^dag W_total Psi",
    }


def run_checks():
    """Run the symbolic identities and write the matching execution report."""
    REPORT.clear()
    REPORT.append("# Certificate: physical open-strip spin-amplitude localization")
    REPORT.append("")
    REPORT.append("Generated by `magnon_topology_strip_localization.py`.")
    REPORT.append("")

    S = sp.symbols("S", positive=True, real=True)
    ur, ui, vr, vi = sp.symbols("u_r u_i v_r v_i", real=True)
    u = ur + sp.I * ui
    v = vr + sp.I * vi
    amplitude_x = sp.sqrt(S / 2) * (u + v)
    amplitude_y = -sp.I * sp.sqrt(S / 2) * (u - v)
    physical_weight = sp.simplify(
        sp.conjugate(amplitude_x) * amplitude_x
        + sp.conjugate(amplitude_y) * amplitude_y
    )
    expected = S * (sp.conjugate(u) * u + sp.conjugate(v) * v)
    check(
        sp.simplify(physical_weight - expected) == 0,
        "sum(|delta S_x|^2, |delta S_y|^2) = S (|u|^2 + |v|^2)",
    )

    S1, S2 = sp.symbols("S_1 S_2", positive=True, real=True)
    a1r, a1i, b1r, b1i = sp.symbols("a1_r a1_i b1_r b1_i", real=True)
    a2r, a2i, b2r, b2i = sp.symbols("a2_r a2_i b2_r b2_i", real=True)
    u1, v1 = a1r + sp.I * a1i, b1r + sp.I * b1i
    u2, v2 = a2r + sp.I * a2i, b2r + sp.I * b2i
    w1 = S1 * (sp.conjugate(u1) * u1 + sp.conjugate(v1) * v1)
    w2 = S2 * (sp.conjugate(u2) * u2 + sp.conjugate(v2) * v2)
    normalized_sum = sp.simplify(w1 / (w1 + w2) + w2 / (w1 + w2))
    check(normalized_sum == 1, "normalized physical site fractions sum to one")

    theta, phi, x = sp.symbols("theta phi x", real=True)
    c, s = sp.cos(theta), sp.sin(theta)
    unitary = sp.Matrix([[c, -sp.exp(-sp.I * phi) * s], [sp.exp(sp.I * phi) * s, c]])
    check(
        (unitary.conjugate().T * unitary - sp.eye(2)).applyfunc(sp.simplify)
        == sp.zeros(2),
        "the parameterized degenerate-subspace basis change is unitary",
    )

    t1, t2, tr, ti = sp.symbols("t_1 t_2 t_r t_i", real=True)
    l1, l2, lr, li = sp.symbols("l_1 l_2 l_r l_i", real=True)
    total = sp.Matrix([[t1, tr + sp.I * ti], [tr - sp.I * ti, t2]])
    edge = sp.Matrix([[l1, lr + sp.I * li], [lr - sp.I * li, l2]])
    characteristic = sp.det(edge - x * total)
    rotated_characteristic = sp.det(
        unitary.conjugate().T * edge * unitary
        - x * unitary.conjugate().T * total * unitary
    )
    check(
        sp.simplify(rotated_characteristic - characteristic) == 0,
        "generalized projected-edge eigenvalues are invariant under unitary mixing",
    )

    report_path = Path(__file__).with_suffix(".md")
    report_path.write_text("\n".join(REPORT) + "\n")
    return dict(named_expressions())


if __name__ == "__main__":
    run_checks()
